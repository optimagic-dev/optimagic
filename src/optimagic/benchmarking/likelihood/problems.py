LIKELIHOOD_SETS: dict[str, tuple[LikelihoodInstance, ...]] = {
    "likelihood_small": LIKELIHOOD_SMALL,
    "likelihood_large": LIKELIHOOD_LARGE,
    "likelihood_misspecified_small": LIKELIHOOD_MISSPECIFIED_SMALL,
    "likelihood_misspecified_large": LIKELIHOOD_MISSPECIFIED_LARGE,
}


def get_likelihood_problems(name: str) -> dict[str, dict[str, Any]]:
    """Simulate the data of a likelihood benchmark set and create its problems.

    Args:
        name: Name of the benchmark set, one of the keys of LIKELIHOOD_SETS.

    Returns:
        Dictionary that maps problem names to problem specifications with the entries
        "fun", "jac", "start_x", "solution_x", "start_criterion",
        "solution_criterion", "lower_bounds", "upper_bounds" and "info". "fun" returns
        the negative log-likelihood contributions and "jac" their jacobian, both
        marked as likelihood functions.

    """
    problems = {}
    for instance in LIKELIHOOD_SETS[name]:
        likelihood = instance.build()
        solution = LIKELIHOOD_SOLUTIONS[instance.name]
        solution_x = np.array(solution["params"])
        n_obs = len(likelihood.fun(solution_x))
        starts = {"good": likelihood.good_start, "bad": likelihood.bad_start}
        for start_name, start_x in starts.items():
            problems[f"{instance.name}_{start_name}_start"] = {
                "fun": mark.likelihood(likelihood.fun),
                "jac": mark.likelihood(likelihood.jac),
                "start_x": start_x,
                "solution_x": solution_x if likelihood.unique_solution else None,
                "start_criterion": float(likelihood.fun(start_x).sum()),
                "solution_criterion": float(likelihood.fun(solution_x).sum()),
                "lower_bounds": likelihood.lower_bounds,
                "upper_bounds": likelihood.upper_bounds,
                "info": {
                    "model": instance.model,
                    "n_params": likelihood.n_params,
                    "n_obs": n_obs,
                    "start": start_name,
                    "misspecification": instance.misspecification,
                    "severity": instance.severity,
                    "has_bounds": likelihood.lower_bounds is not None
                    or likelihood.upper_bounds is not None,
                    "unique_solution": likelihood.unique_solution,
                    "other_local_optima": solution["other_local_optima"],
                    "opg_hessian_ratio": solution["opg_hessian_ratio"],
                },
            }
    return problems
