"""Define the likelihood benchmark sets.

There are four sets of maximum likelihood problems, all framed as minimization of the
negative log-likelihood (the sum of the negative log-likelihood contributions):

- ``likelihood_small``: correctly specified models with 3 to 25 params.
- ``likelihood_large``: correctly specified models with 25 to 150 params.
- ``likelihood_misspecified_small``: misspecified models with 3 to 25 params.
- ``likelihood_misspecified_large``: misspecified models with 25 to 150 params.

Each set is built from instances, i.e. an econometric model fit to a simulated dataset.
Every instance yields two problems, one with good start values (what a practitioner
would choose without knowing the solution) and one with bad start values (far from the
solution). The same econometric model appears with different numbers of params.

Misspecified instances carry a qualitative severity: ``"tiny"``, ``"mild"``,
``"moderate"`` or ``"severe"``. A quantitative measure of misspecification for all
instances is the range of the eigenvalues of inv(H) @ OPG at the solution, where H is
the Hessian and OPG the outer product of the scores. It is one in the population for
correctly specified models.

The ``info`` of each problem also says whether the reference computation found local
optima that are worse than the solution (``"other_local_optima"``), which is the case
for some mixed logit models. Seeds and start values were chosen such that the reference
computation (L-BFGS-B with tight tolerances, followed by Newton steps) reaches the
solution from both the good and the bad start.

Data are simulated with fixed seeds, so the problems are deterministic. The reference
solutions are stored in ``solutions.py``, created by
``.tools/create_likelihood_solutions.py``.

"""

from dataclasses import dataclass
from functools import partial
from typing import Any, Callable, Literal

import numpy as np

from optimagic import mark
from optimagic.benchmarking.likelihood import models
from optimagic.benchmarking.likelihood.models import SimulatedLikelihood
from optimagic.benchmarking.likelihood.solutions import LIKELIHOOD_SOLUTIONS

Severity = Literal["tiny", "mild", "moderate", "severe"]


@dataclass(frozen=True)
class LikelihoodInstance:
    name: str
    """Unique name of the instance, ending with the number of params."""

    build: Callable[[], SimulatedLikelihood]
    """Simulate the data and return the likelihood problem."""

    model: str
    """Short description of the estimated model."""

    misspecification: str | None = None
    """Description of the misspecification; None if correctly specified."""

    severity: Severity | None = None
    """Qualitative severity of the misspecification; None if correctly specified."""


def _instance(
    name: str,
    model: str,
    builder: Callable[..., SimulatedLikelihood],
    misspecification: str | None = None,
    severity: Severity | None = None,
    /,
    **kwargs: Any,
) -> LikelihoodInstance:
    """Create an instance; kwargs are passed to builder."""
    return LikelihoodInstance(
        name=name,
        build=partial(builder, **kwargs),
        model=model,
        misspecification=misspecification,
        severity=severity,
    )


